import { expect, it } from "vitest";
import { clinicDate } from "../src/lib/datetime";

it.each([
  ["2030-01-08T02:59:59Z", "2030-01-07"],
  ["2030-01-08T03:00:00Z", "2030-01-08"],
  ["2030-01-07T23:59:59-03:00", "2030-01-07"],
  ["2030-01-08T11:59:59+09:00", "2030-01-07"],
  ["2030-02-01T02:59:59Z", "2030-01-31"],
  ["2030-02-01T03:00:00Z", "2030-02-01"],
  ["2031-01-01T02:59:59Z", "2030-12-31"],
  ["2031-01-01T03:00:00Z", "2031-01-01"],
  ["2032-03-01T02:59:59Z", "2032-02-29"],
  ["2032-03-01T03:00:00Z", "2032-03-01"],
  // Historical summer time in Sao Paulo used UTC-02, not UTC-03.
  ["2018-01-15T01:59:59Z", "2018-01-14"],
  ["2018-01-15T02:00:00Z", "2018-01-15"],
])("uses the clinic calendar at %s", (instant, expected) => {
  expect(clinicDate(new Date(instant))).toBe(expected);
});
